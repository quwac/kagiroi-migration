package dev.quwac.kagiroi.migration

import kotlinx.serialization.ExperimentalSerializationApi
import kotlinx.serialization.Required
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.descriptors.PolymorphicKind
import kotlinx.serialization.descriptors.SerialDescriptor
import kotlinx.serialization.encoding.CompositeDecoder
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.encodeToJsonElement
import kotlinx.serialization.json.jsonPrimitive

const val MIGRATION_ARTIFACT_FORMAT_VERSION: Int = 1

private const val GENERATED_SQL_NOTICE =
    "-- Generated by Kagiroi Migration. DO NOT EDIT THIS FILE.\n" +
        "-- Change the Kotlin schema and generate a new migration instead.\n\n"
private const val CUSTOM_SQL_NOTICE =
    "-- Custom Kagiroi migration. Edit SQL below the metadata block.\n" +
        "-- Do not edit the generated metadata block.\n\n"

private const val METADATA_OPEN = "/*\nkagiroi:\n"
private const val METADATA_CLOSE = "*/"

internal val migrationArtifactJson = Json {
    encodeDefaults = true
    explicitNulls = false
    prettyPrint = true
    prettyPrintIndent = "  "
    classDiscriminator = "type"
}

@Serializable
enum class MigrationStepKind {
    @SerialName("transactional")
    Transactional,

    @SerialName("nonTransactional")
    NonTransactional,
}

/** An execution checkpoint derived from SQL, with its hash stored in database history. */
@Serializable
data class MigrationArtifactStep(val index: Int, val kind: MigrationStepKind, val sha256: String) {
    init {
        require(index >= 0) { "Migration step index must not be negative" }
        require(SHA256.matches(sha256)) { "Migration step sha256 must be lowercase SHA-256" }
    }
}

/** Public, versioned metadata embedded in a leading SQL block comment. */
@Serializable
data class MigrationArtifactMetadata(
    val formatVersion: Int = MIGRATION_ARTIFACT_FORMAT_VERSION,
    val dialect: String,
    @Required val schemaDelta: SchemaDelta = SchemaDelta(),
) {
    init {
        require(formatVersion == MIGRATION_ARTIFACT_FORMAT_VERSION) {
            "Unsupported Migration Artifact format version: $formatVersion"
        }
        require(MigrationDialect.entries.any { it.id == dialect }) { "Unknown migration dialect: $dialect" }
    }
}

/** Executable SQL with embedded or target-supplied metadata. Handwritten SQL has an empty schema delta. */
data class MigrationArtifact(val metadata: MigrationArtifactMetadata, val body: String) {
    val steps: List<MigrationArtifactStep>
        get() {
            val dialect = MigrationDialect.parse(metadata.dialect)
            val fileHash = sha256Hex("file-v1\u0000${dialect.id}\u0000${canonicalizeSql(body, dialect)}")
            return MigrationScriptParser.parse(body, dialect).steps.mapIndexed { index, step ->
                val hash = sha256Hex(
                    "step-v1\u0000$fileHash\u0000$index\u0000${step.kind}\u0000${stepFingerprint(step)}",
                )
                MigrationArtifactStep(index, step.kind, hash)
            }
        }

    fun rewrite(metadata: MigrationArtifactMetadata): String = writeMigrationArtifact(metadata, body)
}

object MigrationId {
    private val filename = Regex("[0-9]{14}_[a-z][a-z0-9_]*\\.sql")
    private val name = Regex("[a-z][a-z0-9_]*")

    fun isValidFilename(value: String): Boolean = filename.matches(value)

    fun fromFilename(value: String): String {
        require(isValidFilename(value)) { "Invalid migration filename: $value" }
        return value.removeSuffix(".sql")
    }

    fun requireValidName(value: String): String {
        require(name.matches(value)) { "Migration name must be lower snake case and start with a letter: $value" }
        return value
    }
}

/** Reads generated metadata, or treats plain SQL as handwritten using the configured target dialect. */
fun parseMigrationArtifact(text: String, defaultDialect: MigrationDialect? = null): MigrationArtifact {
    val opening = METADATA_OPEN_PATTERN.find(text)
    if (opening == null) {
        require(
            !text.startsWith("-- Generated by Kagiroi Migration.") &&
                !text.startsWith("-- Custom Kagiroi migration.") &&
                !METADATA_MARKER_PATTERN.containsMatchIn(text),
        ) { "Generated migration metadata is missing or malformed; restore it from version control" }
        val dialect = requireNotNull(defaultDialect) { "A configured dialect is required for handwritten SQL" }
        return MigrationArtifact(MigrationArtifactMetadata(dialect = dialect.id), text)
    }
    val metadataStart = opening.range.last + 1
    val metadataEnd = text.indexOf(METADATA_CLOSE, metadataStart)
    require(metadataEnd >= 0) { "Migration artifact metadata comment is not closed" }
    val body = text.substring(metadataEnd + METADATA_CLOSE.length).removeHeaderSeparator()
    return MigrationArtifact(
        metadata = migrationArtifactJson.decodeFromString(
            MigrationArtifactMetadata.serializer(),
            text.substring(metadataStart, metadataEnd).trimEnd('\r', '\n'),
        ),
        body = body,
    )
}

/** Writes the editing notice and deterministic metadata, preserving the raw SQL body exactly. */
fun writeMigrationArtifact(metadata: MigrationArtifactMetadata, body: String): String = buildString {
    append(if (metadata.schemaDelta.operations.isEmpty()) CUSTOM_SQL_NOTICE else GENERATED_SQL_NOTICE)
    append(METADATA_OPEN)
    val serializer = MigrationArtifactMetadata.serializer()
    val encoded = migrationArtifactJson.encodeToJsonElement(serializer, metadata)
    val compact = omitEmptyOptionalArrays(encoded, serializer.descriptor)
    append(migrationArtifactJson.encodeToString(JsonElement.serializer(), compact).replace("*/", "*\\/"))
    append('\n')
    append(METADATA_CLOSE)
    append("\n\n")
    append(body)
}

// Compact only artifact output; canonical schema encoding must retain its existing hash byte source.
@OptIn(ExperimentalSerializationApi::class)
private fun omitEmptyOptionalArrays(value: JsonElement, descriptor: SerialDescriptor): JsonElement {
    val actual = if (descriptor.kind == PolymorphicKind.SEALED && value is JsonObject) {
        val variants = descriptor.getElementDescriptor(1)
        val tag = value.getValue("type").jsonPrimitive.content
        variants.getElementDescriptor(variants.getElementIndex(tag))
    } else {
        descriptor
    }
    return when (value) {
        is JsonObject -> JsonObject(
            value.mapNotNull { (name, child) ->
                val index = actual.getElementIndex(name)
                when {
                    index == CompositeDecoder.UNKNOWN_NAME -> name to child
                    child is JsonArray && child.isEmpty() && actual.isElementOptional(index) -> null
                    else -> name to omitEmptyOptionalArrays(child, actual.getElementDescriptor(index))
                }
            }.toMap(),
        )

        is JsonArray -> JsonArray(value.map { omitEmptyOptionalArrays(it, actual.getElementDescriptor(0)) })

        else -> value
    }
}

/** Stable SHA-256 for an extracted execution step under the artifact lexical rules. */
fun stepFingerprint(step: ParsedExecutionStep): String = sha256Hex(canonicalizeSql(step.sql, step.dialect))

/** Extracts SQL without trusting metadata; an absent header is allowed. */
fun migrationSqlBody(text: String): String {
    val opening = METADATA_OPEN_PATTERN.find(text) ?: return text
    val metadataEnd = text.indexOf(METADATA_CLOSE, opening.range.last + 1)
    require(metadataEnd >= 0) { "Close or remove the metadata comment before regenerating it; SQL is preserved" }
    return text.substring(metadataEnd + METADATA_CLOSE.length).removeHeaderSeparator()
}

/** Builds metadata from SQL and a declared file-level schema change. */
fun createMigrationArtifact(text: String, dialect: MigrationDialect, plan: MigrationPlan): MigrationArtifact {
    val body = migrationSqlBody(text)
    val parsed = MigrationScriptParser.parse(body, dialect)
    require(parsed.steps.isNotEmpty()) { "Migration SQL contains no execution steps" }
    return MigrationArtifact(
        MigrationArtifactMetadata(dialect = dialect.id, schemaDelta = SchemaDelta(plan.operations)),
        body,
    )
}

private val SHA256 = Regex("[0-9a-f]{64}")
private val METADATA_OPEN_PATTERN = Regex("^(?:--[^\\r\\n]*\\r?\\n)*(?:\\r?\\n)?/\\*\\r?\\nkagiroi:\\r?\\n")
private val METADATA_MARKER_PATTERN = Regex("^\\s*(?:--[^\\r\\n]*\\r?\\n\\s*)*/\\*\\s*kagiroi:")

private fun String.removeHeaderSeparator(): String = when {
    startsWith("\r\n\r\n") -> drop("\r\n\r\n".length)
    startsWith("\n\n") -> drop("\n\n".length)
    startsWith("\r\n") -> drop("\r\n".length)
    startsWith("\n") -> drop("\n".length)
    else -> this
}
