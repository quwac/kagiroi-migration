package dev.quwac.kagiroi.gradle

import dev.quwac.kagiroi.migration.MigrationDialect
import dev.quwac.kagiroi.migration.parseMigrationArtifact
import org.gradle.testkit.runner.GradleRunner
import org.gradle.testkit.runner.TaskOutcome
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.nio.file.Files
import java.nio.file.Path
import kotlin.io.path.createDirectories
import kotlin.io.path.readText
import kotlin.test.assertContains
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class KagiroiMigrationPluginFunctionalTest {
    @TempDir
    lateinit var fixture: Path

    @Test
    fun generatesImmediatelyVerifiableSqlWithAFileLevelEditingWarning() {
        writeFixture()
        val generated = runner(
            "kagiroiGenerateMigration",
            "-PkagiroiMigrationName=initial",
            ":app:kagiroiVerifyMigration",
            "--parallel",
        ).build()
        assertEquals(TaskOutcome.SUCCESS, generated.task(":app:kagiroiGenerateMigration")?.outcome)
        assertEquals(TaskOutcome.SUCCESS, generated.task(":app:kagiroiVerifyMigration")?.outcome)
        val directory = fixture.resolve("app/src/main/resources/kagiroi/migrations")
        val migration = Files.list(directory).use { it.findFirst().orElseThrow() }
        assertTrue(migration.fileName.toString().endsWith("_initial.sql"))
        assertFalse(migration.readText().contains("kagiroi:operation"))
        assertTrue(migration.readText().startsWith("-- Generated by Kagiroi Migration. DO NOT EDIT THIS FILE."))
        val artifact = parseMigrationArtifact(migration.readText())
        assertEquals(1, artifact.metadata.formatVersion)
        assertEquals(1, artifact.metadata.schemaDelta.operations.size)
        assertEquals(1, artifact.steps.size)
        runner("kagiroiVerifyMigration").build()
        assertContains(
            runner("kagiroiGenerateMigration", "-PkagiroiMigrationName=unused").build().output,
            "No schema changes.",
        )
        assertEquals(1, Files.list(directory).use { it.count() })
        assertFalse(runner("tasks", "--all").build().output.contains("kagiroiFinalizeMigration"))
    }

    @Test
    fun exportsSchemaWithConfigurationCacheAndRebuildsAfterSchemaChanges() {
        writeFixture()

        val initial = runner("kagiroiExportSchema").build()
        assertEquals(TaskOutcome.SUCCESS, initial.task(":app:kagiroiGenerateSchemaExporter")?.outcome)
        assertEquals(TaskOutcome.SUCCESS, initial.task(":app:compileKotlinJs")?.outcome)
        assertEquals(TaskOutcome.SUCCESS, initial.task(":app:kagiroiExportSchema")?.outcome)
        assertContains(initial.output, "Configuration cache entry stored.")
        val schema = fixture.resolve("app/build/kagiroi/migration/schema.json")
        assertContains(schema.readText(), "users")

        val repeated = runner("kagiroiExportSchema").build()
        assertContains(repeated.output, "Reusing configuration cache.")
        assertEquals(TaskOutcome.UP_TO_DATE, repeated.task(":app:kagiroiExportSchema")?.outcome)

        val source = fixture.resolve("app/src/jsMain/kotlin/example/Schema.kt")
        Files.writeString(
            source,
            source.readText().replace("val name =", "val email = string(\"email\").nullable()\n    val name ="),
        )
        val changed = runner("kagiroiExportSchema").build()
        assertContains(changed.output, "Reusing configuration cache.")
        assertEquals(TaskOutcome.SUCCESS, changed.task(":app:kagiroiExportSchema")?.outcome)
        assertContains(schema.readText(), "email")
    }

    @Test
    fun generatesCustomSqlThatOnlyNeedsItsSqlBodyFilledIn() {
        writeFixture()
        runner("kagiroiGenerateMigration", "-PkagiroiMigrationName=initial").build()
        runner("kagiroiGenerateMigration", "-PkagiroiMigrationName=seed", "-PkagiroiMigrationCustom=true").build()
        val directory = fixture.resolve("app/src/main/resources/kagiroi/migrations")
        val seed = Files.list(
            directory,
        ).use { files -> files.filter { it.fileName.toString().endsWith("_seed.sql") }.findFirst().orElseThrow() }
        val generated = seed.readText()
        assertFalse(generated.contains("kagiroi:"))
        assertTrue(
            parseMigrationArtifact(generated, MigrationDialect.PostgreSql).metadata.schemaDelta.operations.isEmpty(),
        )
        assertContains(runner("kagiroiVerifyMigration").buildAndFail().output, "contains no executable SQL")
        Files.writeString(seed, generated + "INSERT INTO users (name) VALUES ('demo');\n")
        runner("kagiroiVerifyMigration").build()
    }

    @Test
    fun verifies_and_generates_with_a_handwritten_sql_file_created_without_a_task() {
        writeFixture()
        runner("kagiroiGenerateMigration", "-PkagiroiMigrationName=initial").build()
        val directory = fixture.resolve("app/src/main/resources/kagiroi/migrations")
        val seed = directory.resolve("29991231235959_seed.sql")
        val raw = "BEGIN; INSERT INTO users (name) VALUES ('demo'); COMMIT;\n"
        Files.writeString(seed, raw)

        assertContains(
            runner("kagiroiVerifyMigration").build().output,
            "Verified 2 Kagiroi migrations and 2 execution steps.",
        )
        assertContains(
            runner("kagiroiGenerateMigration", "-PkagiroiMigrationName=unused").build().output,
            "No schema changes.",
        )
        assertEquals(raw, seed.readText())
    }

    @Test
    fun regeneratesBrokenMetadataOnlyForAnExplicitLatestFile() {
        writeFixture()
        val directory = fixture.resolve("app/src/main/resources/kagiroi/migrations").createDirectories()
        val migration = directory.resolve("20261101090000_initial.sql")
        val body = "BEGIN; CREATE TABLE users (name TEXT); COMMIT;\nUPDATE users SET name = 'demo';\n"
        Files.writeString(migration, "/*\nkagiroi:\n{broken JSON\n*/\n\n$body")
        assertContains(
            runner("kagiroiRegenerateMigrationMetadata").buildAndFail().output,
            "Use -PkagiroiMigrationFile=",
        )
        regenerate(migration).build()
        val artifact = parseMigrationArtifact(migration.readText())
        assertEquals(body, artifact.body)
        assertEquals(2, artifact.steps.size)
        runner("kagiroiVerifyMigration").build()
        val later = directory.resolve("20261101100000_data.sql")
        Files.writeString(later, migration.readText())
        val original = migration.readText()
        assertContains(
            regenerate(migration).buildAndFail().output,
            "Only the latest migration metadata can be regenerated",
        )
        assertEquals(original, migration.readText())
    }

    @Test
    fun generationAndVerificationDoNotSilentlyRepairBrokenHistory() {
        writeFixture()
        val directory = fixture.resolve("app/src/main/resources/kagiroi/migrations").createDirectories()
        val migration = directory.resolve("20261101090000_initial.sql")
        val broken = "/*\nkagiroi:\n{broken JSON\n*/\nCREATE TABLE users (name TEXT);"
        Files.writeString(migration, broken)
        val failure = runner("kagiroiGenerateMigration", "-PkagiroiMigrationName=next").buildAndFail()
        assertContains(failure.output, "Cannot read migration 20261101090000_initial.sql")
        runner("kagiroiVerifyMigration").buildAndFail()
        assertEquals(broken, migration.readText())
        assertEquals(1, Files.list(directory).use { it.count() })
    }

    @Test
    fun invalidSqlPreventsMetadataRecoveryWithoutRewritingTheFile() {
        writeFixture()
        val directory = fixture.resolve("app/src/main/resources/kagiroi/migrations").createDirectories()
        val migration = directory.resolve("20261101090000_initial.sql")
        val body = "BEGIN; CREATE TABLE users (name TEXT);"
        Files.writeString(migration, body)
        assertContains(regenerate(migration).buildAndFail().output, "Migration transaction is missing COMMIT")
        assertEquals(body, migration.readText())
    }

    private fun regenerate(migration: Path): GradleRunner = runner(
        "kagiroiRegenerateMigrationMetadata",
        "-PkagiroiMigrationFile=${migration.fileName}",
    )

    private fun runner(task: String, vararg arguments: String): GradleRunner = GradleRunner.create()
        .withProjectDir(fixture.toFile())
        .withArguments(
            ":app:$task",
            *arguments,
            "--stacktrace",
            "--console=plain",
            "--configuration-cache",
            "--configuration-cache-problems=fail",
        )
        .withPluginClasspath()

    private fun writeFixture() {
        Files.writeString(
            fixture.resolve("settings.gradle.kts"),
            """
            dependencyResolutionManagement {
                repositories { mavenCentral() }
            }
            rootProject.name = "kagiroi-plugin-fixture"
            include(":app")
            """.trimIndent() + "\n",
        )
        val app = fixture.resolve("app")
        app.createDirectories()
        Files.writeString(
            app.resolve("build.gradle.kts"),
            """
            plugins {
                kotlin("multiplatform") version "2.4.21"
                id("dev.quwac.kagiroi.migration")
            }

            kotlin {
                js { nodejs() }

                sourceSets {
                    jsMain.dependencies {
                        implementation("dev.quwac.kagiroi:kagiroi-schema:${System.getProperty("kagiroi.test.version")}")
                    }
                }
            }

            kagiroi {
                schema.set("example.AppSchema")
                dialect.set("postgresql")
            }
            """.trimIndent() + "\n",
        )
        val source = app.resolve("src/jsMain/kotlin/example")
        source.createDirectories()
        Files.writeString(
            source.resolve("Schema.kt"),
            """
            package example

            import dev.quwac.kagiroi.schema.Table
            import dev.quwac.kagiroi.schema.nullable
            import dev.quwac.kagiroi.schema.schema

            object Users : Table("users") {
                val name = string("name").nullable()
            }

            val AppSchema = schema(Users)
            """.trimIndent() + "\n",
        )
    }
}
